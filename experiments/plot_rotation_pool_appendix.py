"""Appendix G table: the two rotation rows on pool 1 (as printed in the body) and on pool 3, side by side.

Reads only the pool-3 experiment outputs (experiments/rotation_pool/) and writes
paper/tables/table_rotation_pool.tex. Every number is the same artifact the README there names:
linear absolutes and paired deltas from absolute.csv / summary.csv (pool1 rows = footing check F1,
which reproduce Table 1), XGBoost from absolute_xgb.csv, supervised from c1c2/c1c2_absolute.csv.
Pool-1 XGBoost and supervised cells come from the body's own provenance file, paper/build/table1_data.csv.

    python experiments/plot_rotation_pool_appendix.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

repo_root = Path(__file__).resolve().parents[1]
exp = repo_root / "experiments" / "rotation_pool"
out_path = repo_root / "paper" / "tables" / "table_rotation_pool.tex"
CELL = "hann0p3_fbwd"
TASKS = [("rotation", "rotation", "PR-AUC"), ("rotation_period", "rotation period", "$R^2$")]
POOLS = [("pool1", "first pool"), ("pool3", "rotation pool"),
         ("pool3_noflare", "\quad no flare stars"), ("pool3_strict", "\quad strict")]


def one(frame: pd.DataFrame, **where) -> pd.Series | None:
    mask = np.ones(len(frame), dtype=bool)
    for key, value in where.items():
        mask &= (frame[key] == value).to_numpy()
    hit = frame[mask]
    assert len(hit) <= 1, f"{where}: {len(hit)} rows"
    return hit.iloc[0] if len(hit) else None


def fmt(value: float | None, signed: bool = False) -> str:
    if value is None or not np.isfinite(value):
        return "--"
    return f"${value:+.3f}$" if signed else f"{value:.3f}"


def gain_cell(delta: float | None, two_se: float | None) -> str:
    if delta is None or not np.isfinite(delta):
        return "--"
    text = f"{delta:+.3f}"
    if two_se is not None and np.isfinite(two_se) and abs(delta) > two_se:
        return f"$\\mathbf{{{text}}}$"
    return f"${text}$"


def main() -> int:
    absolute = pd.read_csv(exp / "absolute.csv")
    summary = pd.read_csv(exp / "summary.csv")
    xgb = pd.read_csv(exp / "absolute_xgb.csv")
    c1c2 = pd.read_csv(exp / "c1c2" / "c1c2_absolute.csv")
    body = pd.read_csv(repo_root / "paper" / "build" / "table1_data.csv").set_index("task")

    lines = ["% GENERATED by experiments/plot_rotation_pool_appendix.py -- do not hand-edit",
             r"\setlength{\tabcolsep}{2.5pt}",
             r"\begin{tabular}{llrrrrrrrrrr}", r"\toprule",
             r" & & & \multicolumn{5}{c}{linear readout} & \multicolumn{2}{c}{XGBoost} & \multicolumn{2}{c}{supervised} \\",
             r"\cmidrule(lr){4-8}\cmidrule(lr){9-10}\cmidrule(lr){11-12}",
             r"task & population & $n$ (prev.) & features & $\mu$ & fusion & gain & untr.\ gain"
             r" & features & fusion & Conv1D & MLP \\", r"\midrule"]
    for task, label, metric in TASKS:
        for block, pool_label in POOLS:
            head = {"block": block, "task": task, "readout": "mean", "readout_family": "linear"}
            feats = one(absolute, **head, arm_set="features_only", family="features")
            mu = one(absolute, **head, arm_set="mu", family=CELL)
            fusion = one(absolute, **head, arm_set="features_plus_mu", family=CELL)
            gain = one(summary, **head, contrast="fusion_minus_features", family=CELL)
            untr = one(summary, **head, contrast="fusion_minus_features", family="untrained")
            n_test = int(gain["n_test"])
            prev = f" ({gain['prevalence']:.3f})" if np.isfinite(gain["prevalence"]) else ""
            if block == "pool1":
                # the paper's single untrained arm; pool3's untrained row is init 0 of the six (delta_s0)
                untr_gain = float(body.loc[task, "d_features_untrained"])
                xf, xfu = float(body.loc[task, "xgb_features"]), float(body.loc[task, "xgb_fusion"])
                c1, c2 = float(body.loc[task, "c1"]), float(body.loc[task, "c2"])
            else:
                untr_gain = float(untr["delta_s0"]) if untr is not None else np.nan
                xrow = {s: one(xgb, block="pool3", task=task, readout="mean", arm_set=s, family=f)
                        for s, f in [("features_only", "features"), ("features_plus_mu", CELL)]}
                xf = float(xrow["features_only"]["score_mean"]) if block == "pool3" else np.nan
                xfu = float(xrow["features_plus_mu"]["score_mean"]) if block == "pool3" else np.nan
                sup = {a: one(c1c2, task=task, arm=a) for a in ["conv_supervised", "mlp_raw"]}
                c1 = float(sup["conv_supervised"]["score_mean"]) if block == "pool3" else np.nan
                c2 = float(sup["mlp_raw"]["score_mean"]) if block == "pool3" else np.nan
            first = f"{label} ({metric})" if block == "pool1" else ""
            lines.append(f"{first} & {pool_label} & {n_test}{prev} & {fmt(feats['score_mean'])} & "
                         f"{fmt(mu['score_mean'])} & {fmt(fusion['score_mean'])} & "
                         f"{gain_cell(gain['delta_mean'], gain['delta_2se'])} & {fmt(untr_gain, signed=True)} & "
                         f"{fmt(xf)} & {fmt(xfu)} & {fmt(c1)} & {fmt(c2)} \\\\")
        if task == "rotation":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
